// Command notices writes THIRD_PARTY_NOTICES.md: the licence text of every
// module that gg is built from. Binary releases must carry these notices.
//
//	go run ./scripts/notices > THIRD_PARTY_NOTICES.md
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type module struct {
	Path, Version, Dir string
	Main, Indirect     bool
}

var licenceNames = []string{"LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING", "License.txt", "LICENCE"}

func main() {
	out, err := exec.Command("go", "list", "-deps", "-f", "{{with .Module}}{{.Path}}\t{{.Version}}\t{{.Dir}}\t{{.Main}}{{end}}", "./cmd/gg").Output()
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices: go list:", err)
		os.Exit(1)
	}
	seen := map[string]bool{}
	var mods []module
	for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		f := strings.Split(line, "\t")
		if len(f) != 4 || f[2] == "" || seen[f[0]] || f[3] == "true" {
			continue
		}
		seen[f[0]] = true
		mods = append(mods, module{Path: f[0], Version: f[1], Dir: f[2]})
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })

	w := bufio.NewWriter(os.Stdout)
	defer w.Flush()
	fmt.Fprintln(w, "# Third-party notices")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "`gg` is distributed in binary form with the code below. Each licence is reproduced as its author supplied it.")
	fmt.Fprintln(w, "Generated by `go run ./scripts/notices`; regenerate it when `go.mod` changes.")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "| Module | Version |")
	fmt.Fprintln(w, "|---|---|")
	for _, m := range mods {
		fmt.Fprintf(w, "| %s | %s |\n", m.Path, m.Version)
	}
	for _, m := range mods {
		text, name := licence(m.Dir)
		fmt.Fprintf(w, "\n---\n\n## %s %s\n\n", m.Path, m.Version)
		if text == nil {
			fmt.Fprintln(w, "**No licence file found in the module; check its repository before redistributing.**")
			continue
		}
		fmt.Fprintf(w, "_%s_\n\n````\n%s\n````\n", name, strings.TrimRight(string(bytes.ReplaceAll(text, []byte("````"), []byte("'''''"))), "\n"))
	}
}

func licence(dir string) ([]byte, string) {
	for _, n := range licenceNames {
		if b, err := os.ReadFile(filepath.Join(dir, n)); err == nil {
			return b, n
		}
	}
	return nil, ""
}
